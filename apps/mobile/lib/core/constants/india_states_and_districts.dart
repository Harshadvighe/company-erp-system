  /// Returns the sorted list of districts for a given state.
  /// If the state is not matched directly, attempts a case-insensitive search.
  /// If still not found, returns a sensible default list containing the given value.
  static List<String> getDistrictsForState(String state, {String? customDistrict}) {
    final cleanState = state.trim();
    if (cleanState.isEmpty) {
      return ['Pune', 'Mumbai', 'Thane', 'Bangalore', 'Hyderabad', 'Ahmedabad', 'Chennai', 'Noida'];
    }

    // Direct match
    if (districtsByState.containsKey(cleanState)) {
      final list = List<String>.from(districtsByState[cleanState]!);
      if (customDistrict != null &&
          customDistrict.trim().isNotEmpty &&
          !list.any((d) => d.toLowerCase() == customDistrict.trim().toLowerCase())) {
        list.insert(0, customDistrict.trim());
      }
      return list;
    }

    // Case-insensitive match or contains match
    for (final entry in districtsByState.entries) {
      if (entry.key.toLowerCase() == cleanState.toLowerCase() ||
          cleanState.toLowerCase().contains(entry.key.toLowerCase()) ||
          entry.key.toLowerCase().contains(cleanState.toLowerCase())) {
        final list = List<String>.from(entry.value);
        if (customDistrict != null &&
            customDistrict.trim().isNotEmpty &&
            !list.any((d) => d.toLowerCase() == customDistrict.trim().toLowerCase())) {
          list.insert(0, customDistrict.trim());
        }
        return list;
      }
    }

    // Default fallback
    final fallback = [
      'Pune',
      'Mumbai',
      'Thane',
      'Bangalore',
      'Hyderabad',
      'Ahmedabad',
      'Chennai',
      'Noida',
      'Delhi',
      'Kolkata',
    ];
    if (customDistrict != null && customDistrict.trim().isNotEmpty && !fallback.contains(customDistrict.trim())) {
      fallback.insert(0, customDistrict.trim());
    }
    return fallback;
  }

  /// Normalizes state input to standard representation if matched
  static String normalizeState(String state) {
    final s = state.trim().toLowerCase();
    for (final standardState in allStates) {
      if (standardState.toLowerCase() == s || s.contains(standardState.toLowerCase())) {
        return standardState;
      }
    }
    return state.trim();
  }
